"""Bake each character's Windows sort weights (en-US), which Excel's sort orders text by, into
src/pyopenvba/apps/excel/_sort_weights.py, so text sorts as Windows sorts it on every platform.

For each character of Latin and its extensions, the combining marks, Greek, Cyrillic, general punctuation, currency
and letterlike symbols, LCMapStringEx gives the sort key of the character alone, ignoring case and matching it. Its
sections are kept: the primary weights, two bytes each; the diacritic weights; the case weights, one for each way;
and the weight of a character word sort passes over but for ties. _sort.text_key puts them together as Windows does
for a string (see its notes), which tests/test_excel_sort_text.py checks against keys Windows made and Excel's own
sort.

    python scripts/bake_sort_weights.py

Windows only.
"""

from __future__ import annotations

import ctypes
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "pyopenvba" / "apps" / "excel" / "_sort_weights.py"
#: Control characters, a line feed among them, then Latin, its extensions and the rest.
RANGES = [(0x01, 0x1F), (0x20, 0x7E), (0x7F, 0x9F), (0xA0, 0x24F), (0x300, 0x36F), (0x370, 0x3FF), (0x400, 0x52F),
          (0x1E00, 0x1EFF), (0x1F00, 0x1FFF), (0x2000, 0x206F), (0x20A0, 0x20CF), (0x2100, 0x214F)]
#: Two characters whose keys Windows lays out unlike the rest, a diacritic of 0 and two case weights: left out.
ODD = {0x385, 0x1FEE}
LCMAP_SORTKEY, NORM_IGNORECASE = 0x400, 0x1


def sortkey(kernel: ctypes.WinDLL, text: str, flags: int) -> bytes:
    size = kernel.LCMapStringEx("en-US", LCMAP_SORTKEY | flags, text, len(text), None, 0, None, None, None)
    out = ctypes.create_string_buffer(size)
    kernel.LCMapStringEx("en-US", LCMAP_SORTKEY | flags, text, len(text), out, size, None, None, None)
    return out.raw[:size]


def sections(key: bytes) -> list[bytes]:
    found = key.removesuffix(b"\x00").split(b"\x01")
    assert len(found) == 5, key.hex(" ")
    return found


def main() -> None:
    kernel = ctypes.WinDLL("kernel32")
    kernel.LCMapStringEx.argtypes = [ctypes.c_wchar_p, ctypes.c_uint32, ctypes.c_wchar_p, ctypes.c_int,
                                     ctypes.c_void_p, ctypes.c_int, ctypes.c_void_p, ctypes.c_void_p, ctypes.c_void_p]
    rows: list[str] = []
    for low, high in RANGES:
        for code in range(low, high + 1):
            if code in ODD:
                continue
            ignoring = sortkey(kernel, chr(code), NORM_IGNORECASE)
            matching = sortkey(kernel, chr(code), 0)
            # A character Windows gives no weight at all sorts as if it were not there: its weights are all empty.
            primary, accents, ignored_case, extra, skipped = sections(ignoring)
            same_primary, same_accents, case, same_extra, same_skipped = sections(matching)
            assert (primary, accents, extra, skipped) == (same_primary, same_accents, same_extra, same_skipped)
            assert not extra and len(primary) % 2 == 0 and len(skipped) % 4 == 0, hex(code)
            assert all(skipped[at:at + 2] == b"\xff\xff" for at in range(0, len(skipped), 4)), hex(code)
            weights = b"".join(skipped[at + 2:at + 4] for at in range(0, len(skipped), 4))
            rows.append(f"    0x{code:04X}: ({primary.hex()!r}, {accents.hex()!r}, {ignored_case.hex()!r}, "
                        f"{case.hex()!r}, {weights.hex()!r}),")
    header = '''"""Each character's Windows sort weights (en-US), which Excel's sort orders text by: generated by
scripts/bake_sort_weights.py, not edited by hand.

A character maps to its primary weights, two bytes each; its diacritic weights; its case weights ignoring case and
matching it; and, for a character word sort passes over but for ties, its weight there, as hex. _sort.text_key puts
a string's together. A character missing from the table reports itself unsupported.
"""
from __future__ import annotations

from typing import Final

WEIGHTS: Final[dict[int, tuple[str, str, str, str, str]]] = {
'''
    OUT.write_text(header + "\n".join(rows) + "\n}\n", encoding="utf-8")
    print(len(rows), "characters written to", OUT)
    write_keys(kernel)


#: Seeded strings and the sort keys Windows makes of them, which the model's must equal on every platform.
KEYS = Path(__file__).resolve().parent.parent / "tests" / "fixtures" / "sort_keys.json"


def write_keys(kernel: ctypes.WinDLL) -> None:
    import json
    import random

    pick = random.Random(20261025)
    alphabet = [chr(code) for low, high in RANGES for code in range(low, high + 1) if code not in ODD]
    marks = {chr(code) for code in range(0x300, 0x370)} | {chr(code) for code in range(0x483, 0x48A)}
    cases: list[list[str]] = []
    while len(cases) < 1500:
        text = "".join(pick.choice(alphabet) for _ in range(pick.randint(1, 8)))
        if text[0] in marks:
            continue
        cases.append([text, sortkey(kernel, text, NORM_IGNORECASE).hex(), sortkey(kernel, text, 0).hex()])
    lines = ",\n".join(json.dumps(case) for case in cases)
    KEYS.write_text('{"cases": [\n' + lines + "\n]}\n", encoding="utf-8")
    print(len(cases), "strings' keys written to", KEYS)


if __name__ == "__main__":
    main()
