def _wrapped(name: str, text: str) -> str:
    lines = [text[at : at + 110] for at in range(0, len(text), 110)]
    return f'{name} = (\n' + '\n'.join(f'    {line!r}' for line in lines) + '\n)\n'


def _matched(checks: dict[str, str]) -> dict[str, list[int]]:
    """The chart types and styles whose chart part, as the table so far makes it, is the one Excel saved."""
    from pyopenvba.apps.excel import ExcelApplication
    from test_excel_add_chart2 import STYLE_PROBE, normalized

    app = ExcelApplication(sandbox=False)
    app.add_workbook()
    app.add_module(STYLE_PROBE, name='StyleProbe')
    matched: dict[str, list[int]] = {}
    with tempfile.TemporaryDirectory() as folder:
        path = Path(folder) / 'p.xlsx'
        for key, digest in checks.items():
            kind, style = key.split(',')
            try:
                app.run('StyleProbe.Probe', str(path), int(style), int(kind))
            except VBAUnsupportedError:
                continue
            with zipfile.ZipFile(path) as package:
                part = normalized(package.read('xl/charts/chart1.xml').decode('utf-8'))
            if hashlib.sha256(part.encode('utf-8')).hexdigest() == digest:
                matched.setdefault(kind, []).append(int(style))
    return matched


def _theme_lists() -> str:
    """The new workbook's theme's fills and effects, which a style's entries refer to by place."""
    from pyopenvba.powerquery._opc import OpcFile
    from pyopenvba._templates import EMPTY_XLSM_BYTES

    theme = OpcFile.parse(EMPTY_XLSM_BYTES).read('xl/theme/theme1.xml').decode('utf-8')
    fills = theme[theme.index('<a:fillStyleLst>') + len('<a:fillStyleLst>'):theme.index('</a:fillStyleLst>')]
    effects = theme[theme.index('<a:effectStyleLst>'):theme.index('</a:effectStyleLst>')]
    listed = re.findall(r'<a:solidFill>.*?</a:solidFill>|<a:gradFill\b.*?</a:gradFill>', fills, re.S)
    styled = [re.sub(r'</?a:effectStyle>', '', one) for one in re.findall(r'<a:effectStyle>.*?</a:effectStyle>', effects, re.S)]
    return f'\n#: The theme\'s fills and effects.\nTHEME_FILLS: tuple[str, ...] = {tuple(listed)!r}\nTHEME_EFFECTS: tuple[str, ...] = {tuple(styled)!r}\n'


def main() -> None:
    record = json.loads((ROOT / 'tests/fixtures/chart_style_parts.json').read_text(encoding='utf-8'))
    held = json.loads(zlib.decompress(base64.b85decode(record['packed'])).decode('utf-8'))
    added = json.loads((ROOT / 'tests/fixtures/add_chart2.json').read_text(encoding='utf-8'))['styles']
    colours = next(text for key, text in added.items() if key.startswith('colors'))
    defaults = {
        int(kind): int(answer.split()[0]) for kind, answer in record['defaults'].items() if not answer.startswith('Err')
    }
    refused = sorted(int(kind) for kind, answer in record['defaults'].items() if answer.startswith('Err'))
    taken = sorted(int(style) for style, answer in record['answers'].items() if not answer.startswith('Err'))
    assert taken == list(range(taken[0], taken[-1] + 1))
    chosen = sorted({int(key.split(',')[1]) for key in record['checks']} | set(defaults.values()))
    looks = {kind: {str(style): rows[style - taken[0]] for style in chosen} for kind, rows in held['looks'].items()}
    parts = {str(style): held['parts'][str(style)] for style in chosen}
    proven = _matched(record['checks']) if PROVE else {kind: chosen for kind in held['looks']}
    if PROVE:
        kept = {style for styles in proven.values() for style in styles} | set(defaults.values())
        looks = {kind: {style: row for style, row in rows.items() if int(style) in kept} for kind, rows in looks.items()}
        parts = {style: part for style, part in parts.items() if int(style) in kept}
    packed = base64.b85encode(
        zlib.compress(json.dumps({'looks': looks, 'parts': parts, 'layouts': {style: record['layouts'][style] for style in parts}},
                                 separators=(',', ':')).encode('utf-8'), 9)
    )
    body = HEAD + '#: The colours part, the same for every style.\n' + _wrapped('COLORS_PART', colours)
    body += _theme_lists()
    body += f'\n#: The styles it takes beyond the old 1 to 48.\nFIRST_STYLE, LAST_STYLE = {taken[0]}, {taken[-1]}\n'
    body += '\n#: The chart types it refuses, and the style each of the others takes by default.\n'
    body += f'REFUSED_TYPES = frozenset({refused!r})\n'
    lines = textwrap.wrap(repr({int(kind): frozenset(styles) for kind, styles in proven.items()}).replace('frozenset({', '{').replace('})', '}'), 112)
    body += '\n#: For each chart type, the styles that save as Excel saves them.\nPROVEN: dict[int, set[int]] = (\n'
    body += '\n'.join('    ' + line for line in lines) + '\n)\n'
    lines = textwrap.wrap(repr(dict(sorted(defaults.items()))), 112)
    body += 'DEFAULT_STYLES: dict[int, int] = (\n' + '\n'.join('    ' + line for line in lines) + '\n)\n'
    doughnuts = {int(style): tuple(values) for style, values in record['doughnuts'].items()}
    doughnuts = {style: doughnuts.get(style, (50, 0)) for style in chosen}
    lines = textwrap.wrap(repr(dict(sorted(doughnuts.items()))), 112)
    body += '\n#: A doughnut chart\'s hole and first slice at each of those styles.\n'
    body += 'DOUGHNUTS: dict[int, tuple[int, int]] = (\n' + '\n'.join('    ' + line for line in lines) + '\n)\n\n'
    body += _wrapped('_PACKED', packed.decode('ascii'))
    body += TAIL
    OUT.write_text(body, encoding='utf-8')
    print(len(chosen), 'styles,', len(packed), 'packed,', len(body), 'module')


if __name__ == '__main__':
    main()
    PROVE = True
    main()
