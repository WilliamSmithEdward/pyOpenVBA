"""Bake each font's design advances into src/pyopenvba/apps/excel/_font_advances.py, from the font files.

Text in a shape is laid out at these widths, not at the whole pixels GDI gives a cell. It needs Windows, with Aptos Narrow in the
cloud font cache where Office keeps it: open a workbook in it in Excel once.
"""
from __future__ import annotations

import base64
import os
import struct
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
MODULE = ROOT / 'src' / 'pyopenvba' / 'apps' / 'excel' / '_font_advances.py'
CODES = [*range(0x20, 0x7F), *range(0xA0, 0x100)]
FONTS = ('Aptos Narrow', 'Calibri', 'Arial', 'Times New Roman')
STYLES = {'': (False, False), ' Bold': (True, False), ' Italic': (False, True), ' Bold Italic': (True, True)}


def _files() -> dict[str, Path]:
    """Every font file by its full name."""
    found: dict[str, Path] = {}
    cache = Path(os.environ['LOCALAPPDATA']) / 'Microsoft/FontCache/4/CloudFonts'
    for path in [*Path(os.environ['WINDIR'], 'Fonts').glob('*.ttf'), *cache.glob('*/*.ttf')]:
        with TTFont(str(path), lazy=True) as font:
            found[str(font['name'].getDebugName(4))] = path
    return found


def main() -> None:
    files = _files()
    rows: list[str] = []
    for family in FONTS:
        for style, (bold, italic) in STYLES.items():
            name = family + style
            assert name in files, f'{name} is not installed'
            with TTFont(str(files[name]), lazy=True) as font:
                cmap, hmtx, upm = font.getBestCmap(), font['hmtx'], font['head'].unitsPerEm
                units = [hmtx[cmap[code]][0] if code in cmap else 0 for code in CODES]
            packed = base64.b64encode(struct.pack(f'<{len(units)}H', *units)).decode('ascii')
            rows.append(f'    ({family.lower()!r}, {bold}, {italic}): ({upm}, "{packed}"),')
    body = '\n'.join(rows)
    MODULE.write_text(f'''"""Each font's advance per character, in its design units: how wide text is in a shape, where it is not rounded to pixels.

Generated by scripts/bake_font_advances.py from the font files. Do not edit by hand. A character the font has not reads 0, and asks no one.
"""
from __future__ import annotations

import base64
import struct

CODES = (*range(0x20, 0x7F), *range(0xA0, 0x100))
_DATA = {{
{body}
}}


def advances(font: str, bold: bool, italic: bool) -> tuple[int, dict[str, int]] | None:
    """The font's units to the em and each character's advance in them, or None for a font not here."""
    row = _DATA.get((font.lower(), bold, italic))
    if row is None:
        return None
    units = struct.unpack(f"<{{len(CODES)}}H", base64.b64decode(row[1]))
    return row[0], {{chr(code): unit for code, unit in zip(CODES, units, strict=True) if unit}}
''', encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
