"""What the VBA compiler reads about a library's classes: how each member is called and what it returns.

The table is generated by scripts/build_object_inventory.py from the registered type libraries, and imported the first
time a host that has one compiles a procedure. A type the table does not hold is unknown, which binds late and refuses nothing.
"""
from __future__ import annotations

import json
from collections.abc import Sequence
from dataclasses import dataclass
from functools import lru_cache
from typing import Any


class LibraryType(str):
    """A type name that came from a library rather than from a declaration in the project."""


@dataclass(frozen=True, slots=True)
class LibraryClass:
    name: str
    dual: bool
    nonextensible: bool
    default: str
    members: dict[str, list[list[Any]]]

    def reading(self, member: str) -> list[Any] | None:
        """The form of a member that answers a value: a method, or a property's get."""
        return next((form for form in self.members.get(member.lower(), ()) if form[0] in (1, 2)), None)

    @property
    def evaluates(self) -> bool:
        """Whether the class takes DISPID_EVALUATE, which is what target.[text] calls where no member is bound to it."""
        return '_evaluate' in self.members

    def result(self, member: str) -> str | None:
        """What the member returns, '' if nothing, None if the class has no such member."""
        form = self.reading(member)
        return None if form is None else form[3]

    def takes_arguments(self, member: str) -> bool:
        form = self.reading(member)
        return form is not None and (bool(form[4]) or bool(form[2]))

    @property
    def default_result(self) -> str | None:
        return self.result(self.default) if self.default else None


#: A host object of a class no library here describes, such as Office's DocumentProperties, which is no dispinterface.
UNDESCRIBED = LibraryClass('', False, False, '', {})


@lru_cache(maxsize=None)
def find_class(library: str, name: str) -> LibraryClass | None:
    """The class a declared name means in a host's library or in Office's, ``Excel.Range`` as well as ``Range``."""
    from pyopenvba.interpreter._type_library_data import ALIASES, CLASSES

    key = name.rsplit('.', 1)[-1].lower()
    for held in (library, 'office'):
        text = CLASSES.get(f"{held}:{ALIASES.get(held, {}).get(key, key)}")
        if text is not None:
            found = json.loads(text)
            return LibraryClass(found['name'], found['dual'], found['nonextensible'], found['default'], found['members'])
    return None


#: What an interface inherits and the compiler will not let a macro name.
_RESTRICTED = frozenset({'addref', 'release', 'queryinterface', 'gettypeinfocount', 'gettypeinfo', 'getidsofnames', 'invoke'})
_SCALARS = frozenset({'String', 'Long', 'Boolean', 'Double', 'Integer', 'Single', 'Date', 'Currency', 'Byte', 'LongLong'})
_LOOSE = frozenset({'Object', 'Variant'})
WRONG_NUMBER = 'Wrong number of arguments or invalid property assignment'
NOT_OPTIONAL = 'Argument not optional'
NAMED_NOT_FOUND = 'Named argument not found'
NO_FUNCTION = 'Expected Function or variable'
WITH_OBJECT = 'With object must be user-defined type, Object, or Variant'


@dataclass(frozen=True, slots=True)
class CallShape:
    """What the compiler sees of a call's arguments."""

    positional: int = 0
    named: tuple[str, ...] = ()
    #: The places given a literal number or text, which no parameter of a class can take.
    literals: frozenset[int] = frozenset()


def _through_default(library: str, returned: str, shape: CallShape) -> str | None:
    """Arguments on a member that takes none go to the default member of what it returns."""
    if returned in _LOOSE:
        return 'Named arguments not allowed' if shape.named else None
    found = find_class(library, returned) if returned not in _SCALARS and returned else None
    if found is None:
        return WRONG_NUMBER
    # A class with no default member leaves the call to run time.
    return _arguments(library, found.reading(found.default), shape, through=True) if found.default else None


def _arguments(library: str, form: list[Any] | None, shape: CallShape, *, through: bool = False, dual: bool = False) -> str | None:
    if form is None:
        return WRONG_NUMBER
    parameters = [one.split(':') for one in form[4]]
    if not parameters and not form[2]:
        if not shape.positional and not shape.named:
            return None
        # A function takes arguments for what it returns only on a dual class, and only if that is a class: wb.PivotCaches(1).
        hands_on = form[3] and form[3] not in _SCALARS and form[3] not in _LOOSE and dual
        return WRONG_NUMBER if form[0] == 1 and not through and not hands_on else _through_default(library, form[3], shape)
    names = {name.lower() for name, _ in parameters}
    for name in shape.named:
        if name.lower() not in names:
            return NAMED_NOT_FOUND
    for place in sorted(shape.literals):
        if place < len(parameters) and parameters[place][1] not in _SCALARS and parameters[place][1] != 'Variant':
            return 'Type mismatch'
    if shape.positional + len(shape.named) > len(parameters) and not form[2]:
        return WRONG_NUMBER
    given = {name.lower() for name in shape.named}
    if any(name.lower() not in given for name, _ in parameters[shape.positional:form[1]]):
        return NOT_OPTIONAL
    return None


def refusal(library: str, found: LibraryClass, member: str, use: str, shape: CallShape = CallShape()) -> str | None:
    """What VBA's compiler says of this call on a variable of this class, or None if it compiles.

    A use is 'value', 'assign', 'with' or 'statement' (tests/fixtures/vba_compile_kinds.json).
    """
    key = member.lower()
    forms = found.members.get(key)
    if forms is None:
        return 'Method or data member not found' if found.nonextensible else None
    if key in _RESTRICTED:
        return 'Function or interface marked as restricted, or the function uses an Automation type not supported in Visual Basic'
    form = found.reading(key)
    if form is None or (use == 'assign' and any(one[0] in (4, 8) for one in forms)):
        return None
    returned = form[3]
    scalar = returned in _SCALARS
    if use == 'assign' and form[0] == 1 and scalar and found.dual:
        return 'Function call on left-hand side of assignment must return Variant or Object'
    if use != 'assign' or shape.positional or shape.named or form[1]:
        said = _arguments(library, form, shape, dual=found.dual)
        if said is not None:
            return said
    nothing = returned == ''
    if use == 'value':
        return (NO_FUNCTION if found.dual else 'Type mismatch') if nothing else None
    if use == 'with':
        if nothing:
            return NO_FUNCTION if found.dual else WITH_OBJECT
        return WITH_OBJECT if scalar else None
    if use == 'assign':
        if nothing:
            return NO_FUNCTION if found.dual else 'Assignment to constant not permitted'
        if scalar:
            if form[0] == 1 or form[4]:
                return 'Assignment to constant not permitted'
            return "Can't assign to read-only property" if found.dual else WRONG_NUMBER
        if returned in _LOOSE:
            return None
        held = find_class(library, returned)
        return None if held is None else let_refusal(held)
    return None


def indexed_refusal(library: str, held: LibraryClass, shape: CallShape) -> str | None:
    """What the compiler says of v(1) on a variable of this class, which is a call of its default member. A class with none leaves
    it to run time. Dim o As CheckBoxes: o(1) does not compile, as CheckBoxes' default takes nothing, where o.Item(1) does
    (tests/fixtures/old_collection_members.json, on the branch that measured it)."""
    return _arguments(library, held.reading(held.default), shape, through=True) if held.default else None


def let_refusal(held: LibraryClass) -> str | None:
    """What the compiler says of a Let into something of this class, which goes to its default member if it has one."""
    if not held.default:
        return None
    takes = [one for one in held.members[held.default] if one[0] in (4, 8)]
    if not takes:
        reading = held.reading(held.default)
        return NOT_OPTIONAL if reading is not None and reading[0] == 1 and reading[1] else 'Invalid use of property'
    return NOT_OPTIONAL if len(takes[0][4]) > 1 and takes[0][1] > 1 else None


def let_error(held: LibraryClass) -> int | None:
    """The error of a Let into an object of this class bound late, or None if its default member takes it."""
    if not held.default:
        return 438
    if any(one[0] in (4, 8) for one in held.members[held.default]):
        return None
    reading = held.reading(held.default)
    return 438 if reading is not None and reading[4] else 450


#: Value properties on these answer 450 for arguments, where other classes answer 451.
_SCALAR_450 = frozenset({'_Worksheet', 'PageSetup'})


def late_error(found: LibraryClass, member: str, positional: int, named: Sequence[str]) -> int | None:
    """The error of a call bound late that the table decides, or None to let the member answer.

    Too few arguments is 449 or 450 by member, a Variant property's arguments are 450 or 451 by member, and an object's default
    depends on what it holds, so those stay with the member (tests/fixtures/vba_late_errors.json).
    """
    key = member.lower()
    form = found.reading(key)
    if form is None or (not positional and not named):
        return None
    returned = form[3]
    if key in _RESTRICTED:
        return 1004 if named else 438
    names = {one.split(':')[0].lower() for one in form[4]}
    if any(name.lower() not in names for name in named):
        if form[4] or returned in _SCALARS or returned in _LOOSE or not returned:
            return 448 if returned and returned not in _SCALARS and returned not in _LOOSE else 1004
        return None
    if form[4] or form[2]:
        return 450 if positional + len(named) > len(form[4]) and not form[2] else None
    if returned in _SCALARS:
        return 450 if found.name in _SCALAR_450 else 451
    return None


def _late_answer(measured: dict[str, int], number: int, kinds: Sequence[str]) -> int | None:
    if number == 5:
        return measured.get('five')
    wanted = {94: 'null', 13: 'text', 1004: 'bool'}.get(number)
    return measured.get(wanted) if wanted is not None and wanted in kinds else None


def late_let_error(found: LibraryClass, member: str, number: int, kinds: Sequence[str]) -> int | None:
    """What a property set bound late answers for what it answers typed: 0 for no error, None if the typed answer stands."""
    from pyopenvba.interpreter._late_lets import LATE_LETS

    return _late_answer(LATE_LETS.get(f"{found.name.lstrip('_').lower()}.{member.lower()}", {}), number, kinds)


def late_call_error(found: LibraryClass, member: str, number: int, kinds: Sequence[str]) -> int | None:
    """The same for a method given a value that typed it refuses."""
    from pyopenvba.interpreter._late_lets import LATE_CALLS

    return _late_answer(LATE_CALLS.get(f"{found.name.lstrip('_').lower()}.{member.lower()}", {}), number, kinds)


def late_index_error(found: LibraryClass, member: str) -> int | None:
    """What a property that takes nothing says to an index bound late, if it refuses one rather than indexing what it answers."""
    from pyopenvba.interpreter._late_lets import LATE_INDEXES

    return LATE_INDEXES.get(f"{found.name.lstrip('_').lower()}.{member.lower()}")


def reads_double_late(found: LibraryClass, member: str) -> bool:
    from pyopenvba.interpreter._late_lets import LATE_DOUBLES

    return f"{found.name.lstrip('_').lower()}.{member.lower()}" in LATE_DOUBLES


_CUTS_LATE = frozenset({'_Application', '_Worksheet'})
#: Members of those that round and take True as -1 bound late, as VBA does (tests/fixtures/application_identity.json).
_ROUNDS_LATE = frozenset({('_Application', 'featureinstall')})


def late_number(found: LibraryClass, member: str, value: object) -> object:
    """What a numeric property of Application or Worksheet makes of a Variant bound late: True is 1, not -1, and a Long takes a fraction's
    whole part where VBA would round it. A chart or a tab rounds as VBA does (tests/fixtures/vba_late_fractions.json)."""
    puts = next((form for form in found.members.get(member.lower(), ()) if form[0] == 4), None)
    if puts is None or not puts[4] or found.name not in _CUTS_LATE or (found.name, member.lower()) in _ROUNDS_LATE:
        return value
    kind = puts[4][-1].split(':')[-1]
    if kind not in ('Long', 'Double', 'Integer', 'Single'):
        return value
    if isinstance(value, bool):
        return int(value)
    if isinstance(value, float) and kind in ('Long', 'Integer'):
        return int(value)
    return value


def late_arguments(found: LibraryClass, member: str, positional: list[object]) -> list[object]:
    """The same for a method of those: True given to a numeric parameter is 1 (tests/fixtures/method_audit.json)."""
    form = found.reading(member)
    if form is None or found.name not in _CUTS_LATE or form[0] != 1:
        return positional
    types = [one.split(':')[-1] for one in form[4]]
    return [1 if one is True and at < len(types) and types[at] in ('Long', 'Double', 'Integer', 'Single') else one for at, one in enumerate(positional)]


def kinds_of(values: Sequence[object], null: object) -> tuple[str, ...]:
    """Which kinds of value VBA would turn into a parameter's type and fail on."""
    return tuple(kind for kind, there in (('null', any(one is null for one in values)), ('text', any(isinstance(one, str) for one in values)),
                                          ('bool', any(isinstance(one, bool) for one in values))) if there)


def build() -> tuple[str, dict[str, str]]:
    """The Office build and the library versions the table was read from."""
    from pyopenvba.interpreter._type_library_data import EXCEL_BUILD, VERSIONS

    return EXCEL_BUILD, VERSIONS
