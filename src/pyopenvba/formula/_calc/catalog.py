EXCEL_FUNCTIONS = frozenset(_NAMES.split())


def is_excel_function(name: str) -> bool:
    """Whether Excel has a function by this name, as a formula spells it."""
    upper = name.upper()
    if upper.startswith(("_XLFN.", "_XLUDF.", "_XLWS.")):
        return True
    return function_key(name) in EXCEL_FUNCTIONS


