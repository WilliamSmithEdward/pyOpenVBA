@requires_live
def test_lval_pages_are_findable() -> None:
    """
    The live fixture contains long VBA module source stored across LVAL
    (page type 0x08 or page type 0x01 with the literal 'LVAL' tag at +4)
    pages. Verify at least one such page exists.
    """
    with AccessFile(ACCDB) as db:
        found = 0
        for i in range(db.page_count):
            p = db.read_page(i)
            if p[0] == PAGE_TYPE_LVAL or p[4:8] == b"LVAL":
                found += 1
        assert found > 0, "expected at least one LVAL page in the live fixture"


@requires_live
def test_iter_source_rows_finds_comment_lines() -> None:
    """
    The fixture's two modules each contain 1000 distinctive comment lines.
    The pure-Python row scanner must find them all (2000 total) with the
    exact line text used to author the fixture.
    """
    # Each authored line is "' N    This is a VBA comment line with line number"
    # where the number is left-justified in a 5-char field padded with spaces,
    # preceded by one space, followed by one space, then "This is a VBA ...".
    # On disk the leading apostrophe is stripped (see SourceRow.to_source_line).
    expected_texts = {
        f" {n}{' ' * (5 - len(str(n)))}This is a VBA comment line with line number"
        for n in range(1, 1001)
    }
    with AccessFile(ACCDB) as db:
        rows = list(db.iter_source_rows())
        assert all(isinstance(r, SourceRow) for r in rows)
        # Two identical 1000-line modules -> at least 2000 rows.
        assert len(rows) >= 2000, f"only {len(rows)} rows found"
        decoded = {r.text.decode("ascii") for r in rows}
        # Every expected comment-line payload must appear at least once.
        missing = expected_texts - decoded
        assert not missing, f"missing {len(missing)} expected rows: {sorted(missing)[:3]}"


@requires_live
def test_source_row_round_trip_reconstructs_comment_prefix() -> None:
    """
    Comment rows have the leading apostrophe-space stripped on disk.
    SourceRow.to_source_line() must put them back exactly.
    """
    expected_first = "' 1    This is a VBA comment line with line number"
    with AccessFile(ACCDB) as db:
        for row in db.iter_source_rows():
            if row.text.startswith(b" 1    This"):
                assert row.to_source_line() == expected_first
                return
    pytest.fail("did not find the row for source line 1")


