"""Makes src/pyopenvba/apps/excel/_chart_style_table.py from tests/fixtures/chart_style_parts.json and the colours part
in tests/fixtures/add_chart2.json, for the styles some chart type takes by default.

    python scripts/build_chart_styles.py
"""

from __future__ import annotations

import base64
import json
import textwrap
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/pyopenvba/apps/excel/_chart_style_table.py'
HEAD = '''"""What Shapes.AddChart2 brings with it, generated by scripts/build_chart_styles.py from live Excel: the style
part of each style some chart type takes by default, packed, what a chart of the style and type reads besides, and that default
(tests/fixtures/chart_style_parts.json)."""
from __future__ import annotations

import base64
import json
import zlib
from functools import lru_cache
from typing import Any

'''
TAIL = '''

@lru_cache(maxsize=1)
def _unpacked() -> dict[str, Any]:
    return json.loads(zlib.decompress(base64.b85decode(_PACKED)).decode('utf-8'))


def layout(style: int, kind: int) -> list[str]:
    """What a chart of the style and kind reads that its style part does not say: its type, GapWidth and Overlap,
    MajorTickMark of its category and value axes, HasLegend with two series, its first series' MarkerStyle, and
    HasMajorGridlines of its category and value axes."""
    return _unpacked()['looks'][str(kind)][str(style)].split(',')


def style_part(style: int) -> str:
    """The style part Excel writes for the style."""
    return _unpacked()['parts'][str(style)]
'''


def _wrapped(name: str, text: str) -> str:
    lines = [text[at : at + 110] for at in range(0, len(text), 110)]
    return f'{name} = (\n' + '\n'.join(f'    {line!r}' for line in lines) + '\n)\n'


def main() -> None:
    record = json.loads((ROOT / 'tests/fixtures/chart_style_parts.json').read_text(encoding='utf-8'))
    held = json.loads(zlib.decompress(base64.b85decode(record['packed'])).decode('utf-8'))
    added = json.loads((ROOT / 'tests/fixtures/add_chart2.json').read_text(encoding='utf-8'))['styles']
    colours = next(text for key, text in added.items() if key.startswith('colors'))
    defaults = {
        int(kind): int(answer.split()[0]) for kind, answer in record['defaults'].items() if not answer.startswith('Err')
    }
    refused = sorted(int(kind) for kind, answer in record['defaults'].items() if answer.startswith('Err'))
    taken = sorted(int(style) for style, answer in record['answers'].items() if not answer.startswith('Err'))
    assert taken == list(range(taken[0], taken[-1] + 1))
    chosen = sorted(set(defaults.values()))
    looks = {kind: {str(style): rows[style - taken[0]] for style in chosen} for kind, rows in held['looks'].items()}
    parts = {str(style): held['parts'][str(style)] for style in chosen}
    packed = base64.b85encode(
        zlib.compress(json.dumps({'looks': looks, 'parts': parts}, separators=(',', ':')).encode('utf-8'), 9)
    )
    body = HEAD + '#: The colours part, the same for every style.\n' + _wrapped('COLORS_PART', colours)
    body += f'\n#: The styles it takes beyond the old 1 to 48.\nFIRST_STYLE, LAST_STYLE = {taken[0]}, {taken[-1]}\n'
    body += '\n#: The chart types it refuses, and the style each of the others takes by default.\n'
    body += f'REFUSED_TYPES = frozenset({refused!r})\n'
    lines = textwrap.wrap(repr(dict(sorted(defaults.items()))), 112)
    body += 'DEFAULT_STYLES: dict[int, int] = (\n' + '\n'.join('    ' + line for line in lines) + '\n)\n'
    doughnuts = {int(style): tuple(values) for style, values in record['doughnuts'].items()}
    lines = textwrap.wrap(repr(dict(sorted(doughnuts.items()))), 112)
    body += '\n#: A doughnut chart\'s hole and first slice at each of those styles.\n'
    body += 'DOUGHNUTS: dict[int, tuple[int, int]] = (\n' + '\n'.join('    ' + line for line in lines) + '\n)\n\n'
    body += _wrapped('_PACKED', packed.decode('ascii'))
    body += TAIL
    OUT.write_text(body, encoding='utf-8')
    print(len(chosen), 'styles,', len(packed), 'packed,', len(body), 'module')


if __name__ == '__main__':
    main()
