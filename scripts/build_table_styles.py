"""Makes src/pyopenvba/apps/excel/_table_style_table.py from the definitions in tests/fixtures/list_unlist.json.

    python scripts/build_table_styles.py
"""
from __future__ import annotations

import base64
import json
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/pyopenvba/apps/excel/_table_style_table.py'
SIDES = ('left', 'right', 'top', 'bottom', 'vertical', 'horizontal')
LINES = {('1', '2'): 'thin', ('1', '-4138'): 'medium', ('-4119', '4'): 'double', ('1', '4'): 'thick'}
HEAD = '''"""The built-in table styles as TableStyleElements reads them, generated by scripts/build_table_styles.py from live Excel
(tests/fixtures/list_unlist.json). For each style and element that has a format: bold, italic, the font's colour, the fill's
colour, and its sides' line styles and colours, a colour being a kind, a value and a tint."""
from __future__ import annotations

import base64
import json
import zlib
from functools import lru_cache
from typing import Any

'''
TAIL = '''

@lru_cache(maxsize=1)
def table_styles() -> dict[str, dict[str, list[Any]]]:
    return json.loads(zlib.decompress(base64.b85decode(_PACKED)).decode('utf-8'))
'''


def _tristate(text: str) -> bool | None:
    return {'True': True, 'False': False}.get(text)


def _colour(theme: str, tint: str, rgb: str) -> list[object] | None:
    if not theme.startswith('E'):
        return ['theme', int(theme) - 1, round(float(tint) * 32767) if not tint.startswith('E') else 0]
    if rgb.startswith('E'):
        return None
    value = int(rgb)
    return ['rgb', f'FF{value & 255:02X}{value >> 8 & 255:02X}{value >> 16 & 255:02X}', 0]


def _element(fields: list[str]) -> list[object]:
    bold, italic, font_rgb, font_theme, font_tint, pattern, fill_rgb, fill_theme, fill_tint = fields[:9]
    fill = None if pattern.startswith('E') or pattern == '-4142' else _colour(fill_theme, fill_tint, fill_rgb)
    sides: dict[str, list[object]] = {}
    for index, side in enumerate(SIDES):
        style, weight, theme, tint, rgb = fields[9 + index * 5:14 + index * 5]
        if style != '-4142' and not style.startswith('E'):
            sides[side] = [LINES[style, weight], _colour(theme, tint, rgb)]
    return [_tristate(bold), _tristate(italic), _colour(font_theme, font_tint, font_rgb), fill, sides]


def main() -> None:
    record = json.loads((ROOT / 'tests/fixtures/list_unlist.json').read_text(encoding='utf-8'))
    definitions = json.loads(zlib.decompress(base64.b85decode(record['definitions'])))
    styles: dict[str, dict[str, list[object]]] = {}
    for name, text in definitions.items():
        chunks = [chunk.split(',') for chunk in text.split('@')[1:]]
        styles[name] = {chunk[0]: _element(chunk[2:]) for chunk in chunks if chunk[1] == 'True'}
    packed = base64.b85encode(zlib.compress(json.dumps(styles, separators=(',', ':')).encode('utf-8'), 9)).decode('ascii')
    lines = [packed[at:at + 110] for at in range(0, len(packed), 110)]
    OUT.write_text(HEAD + '_PACKED = (\n' + '\n'.join(f'    {line!r}' for line in lines) + '\n)\n' + TAIL, encoding='utf-8')
    print(len(styles), 'styles,', len(packed), 'packed')


if __name__ == '__main__':
    main()
