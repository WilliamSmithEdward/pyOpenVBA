def write_script_keys(kernel: ctypes.WinDLL) -> None:
    import json
    import random

    pick = random.Random(20261107)
    blocks = [[chr(code) for code in range(low, high + 1) if _fits(kernel, code) is not None]
              for low, high in SCRIPT_RANGES]
    blocks.append([chr(code) for code in range(HANGUL[0], HANGUL[1] + 1)])
    blocks.append([chr(code) for code in range(0x20, 0x7F)])
    cases: list[list[str]] = []
    while len(cases) < 1500:
        # Mostly one script at a time, as words are written, with others mixed in now and then.
        home = pick.choice(blocks[:-1])
        text = "".join(pick.choice(home if pick.random() < 0.75 else pick.choice(blocks))
                       for _ in range(pick.randint(1, 8)))
        cases.append([text, _key(kernel, "en-US", text, NORM_IGNORECASE).hex(), _key(kernel, "en-US", text, 0).hex()])
    lines = ",\n".join(json.dumps(case, ensure_ascii=False) for case in cases)
    SCRIPT_KEYS.write_text('{"cases": [\n' + lines + "\n]}\n", encoding="utf-8")
    print(len(cases), "strings' keys written to", SCRIPT_KEYS)


