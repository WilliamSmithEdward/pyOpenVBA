@requires_live
@pytest.mark.parametrize(
    "module_name",
    ["Module1", "Class1", "Module2"],
)
def test_read_vba_module_matches_oracle_byte_for_byte(module_name: str) -> None:
    """
    The decompressed source from pyopenvba.access must match Access COM's
    CodeModule.Lines() output byte-for-byte (after CRLF -> LF normalization
    and trailing-newline stripping, which are artifacts of how the oracle
    writes its file vs. how the on-disk stream stores line endings).
    """
    oracle_path = ORACLE_DIR / f"{module_name}.bas.txt"
    if not oracle_path.exists():
        pytest.skip(f"oracle {oracle_path.name} not present")
    oracle = (
        oracle_path.read_text(encoding="utf-8")
        .replace("\r\n", "\n")
        .rstrip("\n")
    )
    with AccessFile(ACCDB) as db:
        py_src = db.read_vba_module(module_name).replace("\r\n", "\n").rstrip("\n")
    assert py_src == oracle, (
        f"{module_name} mismatch: py len={len(py_src)} oracle len={len(oracle)}"
    )


