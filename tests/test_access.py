# Write path: same-length text patching of the plaintext source store.
#
# Access's authoritative storage for comment bodies and string literals is
# the row-based plaintext store (B9 / E3 markers), NOT the MS-OVBA blob.
# This was verified end-to-end against Access COM and the live VBA editor
# (see docs/architecture.md). The supported write surface is therefore
# same-length byte substitution within those rows.
# ---------------------------------------------------------------------------


@requires_live
def test_replace_text_round_trips_through_disk(tmp_path: Path) -> None:
    """
    Patch a known string literal in Module2 ("This is a test 1" -> a
    same-length replacement), save to a temp copy, reopen, and verify
    both that the bytes round-tripped and that the original buffer is
    not visible in the patched region anymore.
    """
    out = tmp_path / "patched.accdb"
    with AccessFile(ACCDB) as db:
        n = db.replace_text("This is a test 1", "Hello from py!!!")
        assert n >= 1
        db.save(out)
        # The in-memory path should have been updated to the new location.
        assert db.path == out

    # Reopen the saved file and confirm the patch survived to disk.
    raw = out.read_bytes()
    assert b"Hello from py!!!" in raw
    # Count of new strings must be >= replacements we just made.
    assert raw.count(b"Hello from py!!!") >= n


