"""Bake the character widths in tests/fixtures/column_autofit.json into src/pyopenvba/apps/excel/_font_widths.py.

The fixture is what scripts/measure_column_autofit.py measured in live
Excel: for Aptos Narrow 11 and Calibri 11, in each style, the width
AutoFit gives a column holding each character alone, after x, before x and
between two x's, beside x and xx. A character's width is what it adds
between two x's; alone it adds the same, and the style's overhang, which
this checks for every character. The widths are the same under either
Normal font, which this checks too, and are kept for ASCII from the space
to the tilde and Latin-1 from the no-break space to the y with diaeresis,
one letter each.

    python scripts/bake_font_widths.py
"""

from __future__ import annotations

import json
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "tests" / "fixtures" / "column_autofit.json"
MODULE = ROOT / "src" / "pyopenvba" / "apps" / "excel" / "_font_widths.py"
FONTS = ("aptos_narrow", "calibri")
STYLES = {"regular": (False, False), "bold": (True, False), "italic": (False, True), "bold_italic": (True, True)}
CODES = [*range(0x20, 0x7F), *range(0xA0, 0x100)]
ALPHABET = "abcdefghijklmnopqrstuvwxyz"


def table(result: str) -> tuple[int, dict[int, int]]:
    """The overhang a text in the style has past its characters, and each character's width."""
    pieces = dict(piece.split(":") for piece in result.split())
    one, two = int(pieces.pop("x")), int(pieces.pop("xx"))
    overhang = one - 7 - (two - one)
    widths: dict[int, int] = {}
    for code, measured in pieces.items():
        alone, before, after, between = (int(value) for value in measured.split(","))
        width = between - two
        # Nothing reaches past a character at either end of a text but the style's overhang.
        assert alone - 7 == width + overhang and before == after == one + width, (code, measured)
        widths[int(code)] = width
    return overhang, widths


def main() -> None:
    fixture = json.loads(FIXTURE.read_text(encoding="utf-8"))
    results = {probe["name"]: probe["result"] for probe in fixture["probes"]}
    lines: list[str] = []
    for font in FONTS:
        for style, (bold, italic) in STYLES.items():
            overhang, widths = table(results[f"glyphs_aptos_narrow_{font}_{style}"])
            assert (overhang, widths) == table(results[f"glyphs_calibri_{font}_{style}"]), (font, style)
            letters = "".join(ALPHABET[widths[code]] for code in CODES)
            name = font.replace("_", " ")
            chunks = textwrap.wrap(letters, 100)
            lines.append(f"    ({name!r}, {bold}, {italic}): (")
            lines.extend(f'        "{chunk}"' for chunk in chunks)
            lines.append("    ),")
    MODULE.write_text(f'''"""How wide Excel measures each character for AutoFit, on a 96-DPI display.

Generated by scripts/bake_font_widths.py from tests/fixtures/column_autofit.json,
which scripts/measure_column_autofit.py measured in live Excel. For Aptos
Narrow and Calibri at 11pt, in regular, bold, italic and bold italic, each
table holds a character's width in pixels, one letter each ("a" is 0), for
ASCII from the space to the tilde and Latin-1 from the no-break space to
the y with diaeresis. The widths are GDI's, whole pixels that add up along
a text; for Windows-1252's other characters GDI's widths depend on their
neighbours, so they are not here. Do not edit by hand.
"""

from __future__ import annotations

from functools import cache

#: The characters each table holds, in order.
CODES = (*range(0x20, 0x7F), *range(0xA0, 0x100))
_ALPHABET = "{ALPHABET}"
#: (font, bold, italic) -> each character's width, one letter each.
_TABLES: dict[tuple[str, bool, bool], str] = {{
{chr(10).join(lines)}
}}


@cache
def widths(font: str, bold: bool, italic: bool) -> dict[str, int] | None:
    """Each character's width in pixels in a font and style at 11pt, or None for one that was not measured."""
    letters = _TABLES.get((font.lower(), bold, italic))
    if letters is None:
        return None
    return {{chr(code): _ALPHABET.index(letter) for code, letter in zip(CODES, letters)}}
''', encoding="utf-8")
    print(f"wrote {MODULE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
