"""Generates src/pyopenvba/apps/excel/_worksheet_function_refusals.py from tests/fixtures/worksheet_function_kinds.json: which
kinds of value each worksheet function refuses with 1004, argument by argument, as Excel answered late bound. Only kinds of
value go in, never particular numbers, whose answers follow each function's own rules.

    python scripts/build_worksheet_function_refusals.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/pyopenvba/apps/excel/_worksheet_function_refusals.py'
#: What the probe gives, and the kind of value it stands for.
KINDS = {'x = Null': 'null', 'x = Empty': 'empty', 'x = True': 'true', 'x = False': 'false',
         'Set x = ws.Range("A1:A3")': 'cells', 'Set x = ws.Range("Z9")': 'empty cell', 'x = Array(1, 2)': 'array'}


def _kind_given(argument: str) -> str:
    """The kind of an argument of the call Excel answered, whose kind in that place is plainly taken."""
    if 'Array(' in argument or argument.startswith('{'):
        return 'array'
    if ':' in argument and 'Range' in argument:
        return 'cells'
    return {'True': 'true', 'False': 'false'}.get(argument, 'other')


def split_arguments(text: str) -> list[str]:
    parts: list[str] = []
    depth, quoted, start = 0, False, 0
    for at, char in enumerate(text):
        if char == '"':
            quoted = not quoted
        elif not quoted and char in '({':
            depth += 1
        elif not quoted and char in ')}':
            depth -= 1
        elif not quoted and not depth and char == ',':
            parts.append(text[start:at].strip())
            start = at + 1
    parts.append(text[start:].strip())
    return parts


def main() -> None:
    record = json.loads((ROOT / 'tests/fixtures/worksheet_function_kinds.json').read_text(encoding='utf-8'))
    table: dict[str, dict[int, set[str]]] = {}
    for name, cases in record['functions'].items():
        # A refusal can come of how the value meets the other arguments, as ranges of different sizes do. What the call
        # that was answered gives in a place is taken there, so what is refused there is another kind.
        answered = split_arguments(cases[0][0][cases[0][0].index('(') + 1:-1])
        for call, late, _typed in cases:
            given, _, rest = call.partition(': v = f.')
            kind = KINDS.get(given)
            if kind is None or late != 'e1004':
                continue
            arguments = split_arguments(rest[rest.index('(') + 1:-1])
            place = arguments.index('x')
            # XLookup's result is refused by its size, its fallback Null only by finding nothing with no fallback, and a
            # lone Null by the rule for any last argument: none of them by its kind.
            if (name == 'XLookup' and ((place == 2 and kind not in ('null', 'empty')) or (place == 3 and kind == 'null'))) or (name == 'Unique' and kind == 'null'):
                continue
            # XMatch's value and match mode are refused only by what the search then finds, which the probe's numbers did
            # not hold: a logical, a blank or Null is looked for, and a blank or False mode is 0 (tests/fixtures/xlookup_rounds.json).
            if name == 'XMatch' and (place == 0 or (place == 2 and kind != 'null')):
                continue
            # Several ranges or arrays together can refuse by their sizes alone.
            if kind in ('cells', 'array') and any(_kind_given(one) in ('cells', 'array') for one in answered):
                continue
            if _kind_given(answered[place]) != kind:
                table.setdefault(name.lower(), {}).setdefault(place, set()).add(kind)
    lines = ['"""Which kinds of value each worksheet function refuses with 1004, argument by argument.', '',
             'Generated by scripts/build_worksheet_function_refusals.py from tests/fixtures/worksheet_function_kinds.json.', '"""', '',
             'from __future__ import annotations', '', 'REFUSALS: dict[str, dict[int, frozenset[str]]] = {']
    for name in sorted(table):
        places = ', '.join(f'{place}: frozenset({sorted(kinds)!r})' for place, kinds in sorted(table[name].items()))
        lines.append(f'    {name!r}: {{{places}}},')
    lines += ['}', '']
    OUT.write_text('\n'.join(lines), encoding='utf-8')
    print(len(table), 'functions', OUT.stat().st_size, 'bytes')


if __name__ == '__main__':
    main()
