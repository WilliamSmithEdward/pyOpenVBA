SCRIPTS_OUT = OUT.with_name("_sort_weights_scripts.py")
#: Hebrew, Arabic and its supplement, Thai, the Hangul compatibility jamo and the Arabic presentation forms: weighed
#: one character at a time as the en-US table is, and the same under every locale that was tried (en-US, ja-JP,
#: ko-KR, he-IL, ar-SA, th-TH). The conjoining jamo, U+1100 to U+11FF, are left out: Windows weighs a run of them as
#: the syllable they spell, so they report themselves unsupported.
SCRIPT_RANGES = [(0x0591, 0x05F4), (0x0600, 0x06FF), (0x0750, 0x077F), (0x0E01, 0x0E5B), (0x3131, 0x318E),
                 (0xFB50, 0xFDFF), (0xFE70, 0xFEFF)]
#: The Hangul syllables, U+AC00 to U+D7A3: two-byte primary weights in runs, each next syllable weighing one more.
HANGUL = (0xAC00, 0xD7A3)
SCRIPT_LOCALES = ("en-US", "ja-JP", "ko-KR", "he-IL", "ar-SA", "th-TH")


def _fits(kernel: ctypes.WinDLL, code: int) -> tuple[bytes, bytes, bytes, bytes, bytes] | None:
    """A character's weights in the en-US table's layout, the same under every locale tried; None for one whose key
    lays out otherwise, an Arabic ligature with more sections among them, which is left out."""
    ignoring = _sections_of(kernel, "en-US", chr(code), NORM_IGNORECASE)
    matching = _sections_of(kernel, "en-US", chr(code), 0)
    for locale in SCRIPT_LOCALES[1:]:
        assert ignoring == _sections_of(kernel, locale, chr(code), NORM_IGNORECASE), (locale, hex(code))
        assert matching == _sections_of(kernel, locale, chr(code), 0), (locale, hex(code))
    if len(ignoring) != 5 or len(matching) != 5:
        return None
    primary, accents, ignored_case, extra, skipped = ignoring
    if extra or len(primary) % 2 or len(skipped) % 4 or (primary, accents, skipped) != (
            matching[0], matching[1], matching[4]) or matching[3]:
        return None
    if any(skipped[at:at + 2] != b"\xff\xff" for at in range(0, len(skipped), 4)):
        return None
    return primary, accents, ignored_case, matching[2], b"".join(skipped[at + 2:at + 4]
                                                                 for at in range(0, len(skipped), 4))


def write_scripts(kernel: ctypes.WinDLL) -> None:
    """Bake Hebrew, Arabic, Thai and Hangul: SCRIPTS in the en-US table's layout, HANGUL's syllables as runs."""
    rows: list[str] = []
    left_out: list[int] = []
    for low, high in SCRIPT_RANGES:
        for code in range(low, high + 1):
            found = _fits(kernel, code)
            if found is None:
                left_out.append(code)
                continue
            rows.append(f"    0x{code:04X}: ({', '.join(repr(part.hex()) for part in found)}),")
    runs: list[tuple[int, int, int]] = []
    for code in range(HANGUL[0], HANGUL[1] + 1):
        found = _fits(kernel, code)
        assert found is not None and len(found[0]) == 2 and not any(found[2:]), hex(code)
        if found[1]:
            # A syllable with a diacritic weight of its own goes among SCRIPTS.
            rows.append(f"    0x{code:04X}: ({', '.join(repr(part.hex()) for part in found)}),")
            continue
        weight = int.from_bytes(found[0], "big")
        if runs and runs[-1][0] + runs[-1][2] == code and runs[-1][1] + runs[-1][2] == weight:
            runs[-1] = (runs[-1][0], runs[-1][1], runs[-1][2] + 1)
        else:
            runs.append((code, weight, 1))
    rows.sort(key=lambda row: int(row.split(":")[0], 16))
    header = '''"""Windows sort weights for Hebrew, Arabic, Thai and Hangul, which Excel's sort orders text by: generated by
scripts/bake_sort_weights.py, not edited by hand.

SCRIPTS maps a character to its weights in _sort_weights' layout: primary, diacritic, case ignoring and matching it,
and its weight where word sort passes over it, as hex. HANGUL gives the syllables Windows weighs with a primary weight
alone, as runs of (first syllable, its weight, how many), each next syllable weighing one more. The conjoining jamo,
which Windows weighs as the syllable a run of them spells, and the Arabic ligatures whose keys lay out otherwise are
missing, so they report themselves unsupported.
"""
from __future__ import annotations

from typing import Final

SCRIPTS: Final[dict[int, tuple[str, str, str, str, str]]] = {
'''
    text = (header + "\n".join(rows) + "\n}\n\nHANGUL: Final[tuple[tuple[int, int, int], ...]] = (\n"
            + "".join(f"    (0x{code:04X}, 0x{weight:04X}, {count}),\n" for code, weight, count in runs) + ")\n")
    SCRIPTS_OUT.write_text(text, encoding="utf-8")
    print(len(rows), "characters,", len(runs), "Hangul runs written to", SCRIPTS_OUT, "; left out:",
          " ".join(f"{code:04X}" for code in left_out))
    write_script_keys(kernel)


